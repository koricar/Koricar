const sortedKeys = (o: Record<string, string>) => Object.keys(o).sort((a, b) => b.length - a.length);
const WORD_KEYS = sortedKeys(WORDS);
const MODEL_KEYS = sortedKeys(MODELS);

export function translateModelAr(name: string | null | undefined): string {
  let s = String(name ?? "");
  if (!/[가-힣]/.test(s)) return s;
  s = s.replace(/(\d+)\s*세대/g, "الجيل $1").replace(/(\d+)\s*인승/g, "$1 مقاعد").replace(/(\d+)\s*시리즈/g, "الفئة $1");
  s = s.replace(/([A-Za-z0-9]+)\s*-?\s*클래스/g, "الفئة $1");
  const H = "\\uAC00-\\uD7A3";
  const swap = (k: string, v: string) => { s = s.replace(new RegExp(`(?<![${H}])${k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`, "g"), ` ${v} `); };
  for (const k of WORD_KEYS) swap(k, WORDS[k]);
  for (const k of MODEL_KEYS) swap(k, MODELS[k]);
  return s.replace(/\s+/g, " ").replace(/\(\s+/g, "(").replace(/\s+\)/g, ")").trim();
}


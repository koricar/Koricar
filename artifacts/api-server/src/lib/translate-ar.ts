export function translatePartAr(part: string | null | undefined): string {
  const raw = String(part ?? "");
  if (!raw) return raw;
  let side = "";
  for (const [k, v] of SIDE) if (raw.includes(k)) side = v;
    const flat = raw.replace(/\s+/g, "").replace(/\(좌\)|\(우\)|\(볼트체결부품\)/g, "");
  const letter = raw.match(/\(([A-D])\)/)?.[1];
  for (const [kr, ar] of PARTS) {
    if (flat.includes(kr)) return `${ar}${kr.includes("필러") && letter && !ar.endsWith(letter) ? " " + letter : ""}${side}`;
  }
  return raw;
}
